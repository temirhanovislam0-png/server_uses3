import bcrypt from "bcrypt"; // Импортируем библиотеку bcrypt для работы с криптографией

class HashService { // Создаем класс для инкапсуляции логики работы с паролями
  async hashPassword(password) { // Асинхронный метод для создания хеша из открытого пароля
    try { // Начинаем блок try, чтобы перехватить возможные ошибки выполнения
      const salt = await bcrypt.genSalt(10); // Генерируем "соль" (10 раундов) для защиты от взлома
      const hash = await bcrypt.hash(password, salt); // Хэшируем пароль, применяя к нему полученную соль
      return hash; // Возвращаем итоговый зашифрованный хеш
    } catch (err) { // Если в блоке try произошла ошибка, перехватываем её
      throw new Error("Ошибка при хешировании"); // Выбрасываем новую ошибку с понятным сообщением
    } // Закрываем блок catch
  } // Закрываем метод hashPassword

  async comparePassword(password, hash) { // Асинхронный метод для проверки (сравнения) пароля
    try { // Начинаем блок try для отлова ошибок
      return await bcrypt.compare(password, hash); // Сравниваем пароль и хеш, возвращаем true (совпало) или false
    } catch (error) { // Если произошла ошибка (например, передан невалидный хеш)
      throw new Error("Ошибка при сравнении паролей"); // Выбрасываем ошибку с сообщением
    } // Закрываем блок catch
  } // Закрываем метод comparePassword
} // Закрываем класс HashService

export default new HashService(); // Экспортируем единственный экземпляр класса (паттерн Singleton) для использования в других файлах